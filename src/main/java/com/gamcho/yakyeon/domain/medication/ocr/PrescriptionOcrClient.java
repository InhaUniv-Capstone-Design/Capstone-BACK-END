package com.gamcho.yakyeon.domain.medication.ocr;

/**
 * 처방전 이미지를 읽어내는 OCR 엔진. 구현체만 바꾸면 서비스·컨트롤러는 그대로 동작한다.
 * 지금은 Mock(고정 응답)이고, 이후 Tesseract나 외부 OCR API 구현체로 교체한다.
 *
 * 구현체를 만들 때 지킬 것
 *  - 이미지는 처방전이라 이름·병명 등 민감정보가 담겨 있다. 디스크·DB·로그 어디에도 남기지 말 것 (메모리에서만 처리).
 *  - 외부 서비스로 보내는 구현이라면 그 서비스의 보관·학습 정책을 먼저 확인하고, 개인정보 처리 위탁 문서에 반영할 것.
 *  - 이미지는 형식(JPEG/PNG)과 크기가 검증된 뒤에 넘어오지만, 악성 파일일 가능성은 여전히 있다.
 *    실제 이미지 디코더는 격리된 환경(별도 프로세스·컨테이너, 시간·메모리 제한)에서 돌릴 것.
 *  - 시간이 오래 걸릴 수 있으니 호출 시간 제한을 둘 것 (이 호출은 DB 트랜잭션 밖에서 이뤄진다).
 */
public interface PrescriptionOcrClient {

    OcrResult recognize(byte[] image);
}